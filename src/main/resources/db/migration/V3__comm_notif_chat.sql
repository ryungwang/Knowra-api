-- V3: 커뮤니티 알림 구독 + 1:1 채팅
--
-- 커뮤니티 알림: 멤버 행(tbl_comm_mbr)에 NOTIF_YN 한 칸을 둔다. 구독은 멤버에게만 있는
--   개념이라 별도 테이블이 필요 없고, 탈퇴하면 같이 사라진다. 기존 멤버는 'N'(조용히),
--   새로 가입하는 멤버는 서비스가 'Y' 로 넣는다 — 참여한 직후엔 새 글을 보고 싶어 한다.
--   공지(NOTICE)는 구독 여부와 무관하게 전 멤버에게 간다.
--
-- 채팅: 1:1 대화만 있다(room_typ='DM'). 같은 두 사람 사이에 방이 둘 생기지 않도록
--   DM_KEY('작은SN:큰SN') 에 UNIQUE 를 건다. 읽음은 멤버별 LAST_READ_MSG_SN 으로 센다 —
--   메시지마다 읽음 행을 두면 메시지 수만큼 행이 늘어난다.
-- ============================================================================

-- ── 1. 커뮤니티 알림 구독 ────────────────────────────────────────────────
ALTER TABLE knowra_community.tbl_comm_mbr ADD COLUMN notif_yn VARCHAR(1) NOT NULL DEFAULT 'N';
COMMENT ON COLUMN knowra_community.tbl_comm_mbr.notif_yn IS '새 글 알림 구독 여부 (공지는 구독과 무관하게 전 멤버)';

-- ── 2. 채팅 ────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS knowra_user.tbl_chat_room
(
    ROOM_SN     BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    ROOM_TYP    VARCHAR(10) NOT NULL DEFAULT 'DM',
    DM_KEY      VARCHAR(50) DEFAULT NULL,
    LAST_MSG_SN BIGINT DEFAULT NULL,
    LAST_MSG_AT TIMESTAMP(6) DEFAULT NULL,
    FRST_CRT_DT TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (ROOM_SN),
    CONSTRAINT UK_CHAT_ROOM_DM UNIQUE (DM_KEY)
);
COMMENT ON COLUMN knowra_user.tbl_chat_room.dm_key IS '1:1 방 중복 방지 키 — min(userSn):max(userSn)';

CREATE TABLE IF NOT EXISTS knowra_user.tbl_chat_room_mbr
(
    ROOM_MBR_SN      BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    ROOM_SN          BIGINT NOT NULL,
    USER_SN          BIGINT NOT NULL,
    LAST_READ_MSG_SN BIGINT NOT NULL DEFAULT 0,
    FRST_CRT_DT      TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (ROOM_MBR_SN),
    CONSTRAINT UK_CHAT_ROOM_MBR UNIQUE (ROOM_SN, USER_SN),
    CONSTRAINT FK_CHAT_ROOM_MBR_ROOM FOREIGN KEY (ROOM_SN) REFERENCES knowra_user.tbl_chat_room (ROOM_SN),
    CONSTRAINT FK_CHAT_ROOM_MBR_USER FOREIGN KEY (USER_SN) REFERENCES knowra_user.tbl_user (USER_SN)
);
CREATE INDEX IF NOT EXISTS idx_chat_room_mbr_user ON knowra_user.tbl_chat_room_mbr (USER_SN);

CREATE TABLE IF NOT EXISTS knowra_user.tbl_chat_msg
(
    MSG_SN      BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    ROOM_SN     BIGINT NOT NULL,
    USER_SN     BIGINT NOT NULL,
    MSG_CNTNT   TEXT NOT NULL,
    FRST_CRT_DT TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (MSG_SN),
    CONSTRAINT FK_CHAT_MSG_ROOM FOREIGN KEY (ROOM_SN) REFERENCES knowra_user.tbl_chat_room (ROOM_SN)
);
CREATE INDEX IF NOT EXISTS idx_chat_msg_room ON knowra_user.tbl_chat_msg (ROOM_SN, MSG_SN);
