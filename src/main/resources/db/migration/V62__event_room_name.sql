-- V62: 모임 대화방 이름에서 「모임 · 」 머리말을 뗀다
--
-- 예전엔 서버가 이름을 「모임 · 제목」으로 저장해 다른 언어 화면·푸시에도 한국어 머리말이 나왔다.
-- 이제 이름에는 모임 제목만 두고, 화면·푸시가 보는 사람 언어로 머리말을 붙인다(EVENT_SN 이 있으면 모임 방).
-- ============================================================================
UPDATE knowra_user.tbl_chat_room SET name = substring(name FROM 5)
WHERE event_sn IS NOT NULL AND name LIKE '모임 · %';
