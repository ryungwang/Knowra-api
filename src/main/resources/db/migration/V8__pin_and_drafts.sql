ALTER TABLE knowra_post.tbl_post ADD COLUMN IF NOT EXISTS PINNED_AT TIMESTAMP(6) DEFAULT NULL;
CREATE INDEX IF NOT EXISTS idx_post_comm_pinned ON knowra_post.tbl_post (COMM_SN, PINNED_AT) WHERE PINNED_AT IS NOT NULL;

CREATE TABLE IF NOT EXISTS knowra_post.tbl_post_draft
(
    DRAFT_SN    BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    USER_SN     BIGINT NOT NULL,
    COMM_SN     BIGINT DEFAULT NULL,
    TITLE       VARCHAR(300) NOT NULL DEFAULT '',
    CONTENT     TEXT NOT NULL DEFAULT '',
    TAGS        VARCHAR(1000) NOT NULL DEFAULT '',
    UPDATED_AT  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (DRAFT_SN),
    CONSTRAINT FK_DRAFT_USER FOREIGN KEY (USER_SN) REFERENCES knowra_user.tbl_user (USER_SN) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_draft_user ON knowra_post.tbl_post_draft (USER_SN, UPDATED_AT DESC);
