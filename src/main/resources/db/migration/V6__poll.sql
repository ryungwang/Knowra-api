-- V6: 투표 — 글 하나에 투표 하나(선택지 2~6개, 단일/복수 선택, 마감 시각).
--
-- 결과는 투표했거나 마감됐거나 글쓴이일 때만 보여 준다(PollService) — 중간 결과가 표를 끌고 가지 않게.
-- 표는 마감 전까지 바꿀 수 있다. 같은 사람이 같은 선택지에 두 번 들어가지 않게 UNIQUE.
-- VOTE_CNT 는 표를 바꿀 때마다 다시 센다(증감 누적이 아니라) — 어긋날 수가 없다.
-- ============================================================================
CREATE TABLE IF NOT EXISTS knowra_post.tbl_poll
(
    POLL_SN     BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    POST_SN     BIGINT NOT NULL,
    MULTI_YN    VARCHAR(1) NOT NULL DEFAULT 'N',
    ENDS_AT     TIMESTAMP(6) NOT NULL,
    FRST_CRT_DT TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (POLL_SN),
    CONSTRAINT UK_POLL_POST UNIQUE (POST_SN),
    CONSTRAINT FK_POLL_POST FOREIGN KEY (POST_SN) REFERENCES knowra_post.tbl_post (POST_SN) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS knowra_post.tbl_poll_option
(
    OPTION_SN BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    POLL_SN   BIGINT NOT NULL,
    ORD       INT NOT NULL,
    LABEL     VARCHAR(80) NOT NULL,
    VOTE_CNT  INT NOT NULL DEFAULT 0,
    PRIMARY KEY (OPTION_SN),
    CONSTRAINT FK_POLL_OPTION_POLL FOREIGN KEY (POLL_SN) REFERENCES knowra_post.tbl_poll (POLL_SN) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_poll_option_poll ON knowra_post.tbl_poll_option (POLL_SN, ORD);

CREATE TABLE IF NOT EXISTS knowra_post.tbl_poll_vote
(
    VOTE_SN     BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    POLL_SN     BIGINT NOT NULL,
    OPTION_SN   BIGINT NOT NULL,
    USER_SN     BIGINT NOT NULL,
    FRST_CRT_DT TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (VOTE_SN),
    CONSTRAINT UK_POLL_VOTE UNIQUE (POLL_SN, USER_SN, OPTION_SN),
    CONSTRAINT FK_POLL_VOTE_OPTION FOREIGN KEY (OPTION_SN) REFERENCES knowra_post.tbl_poll_option (OPTION_SN) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_poll_vote_user ON knowra_post.tbl_poll_vote (POLL_SN, USER_SN);
