--   참석하겠다던 사람에게 취소를 알려야 하니까). 장소는 글자, 온라인이면 링크(http/https 만).
--   REMINDED_DAY/HOUR: 하루 전·한 시간 전 알림을 이미 보냈는가(스케줄러가 한 번만 보내게).
