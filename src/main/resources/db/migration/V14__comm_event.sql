CREATE TABLE IF NOT EXISTS knowra_community.tbl_comm_event
(
    EVENT_SN      BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    COMM_SN       BIGINT NOT NULL,
    CREATED_BY    BIGINT NOT NULL,
    TITLE         VARCHAR(80) NOT NULL,
    DESCR         VARCHAR(2000) NOT NULL DEFAULT '',
    STARTS_AT     TIMESTAMP(6) NOT NULL,
    ENDS_AT       TIMESTAMP(6) DEFAULT NULL,
    PLACE         VARCHAR(120) DEFAULT NULL,
    ONLINE_URL    VARCHAR(300) DEFAULT NULL,
    CAPACITY      INT DEFAULT NULL,
    STAT          VARCHAR(10) NOT NULL DEFAULT 'ACTIVE',
    REMINDED_DAY  BOOLEAN NOT NULL DEFAULT FALSE,
    REMINDED_HOUR BOOLEAN NOT NULL DEFAULT FALSE,
    FRST_CRT_DT   TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (EVENT_SN)
);
CREATE INDEX IF NOT EXISTS idx_comm_event ON knowra_community.tbl_comm_event (COMM_SN, STARTS_AT);
CREATE INDEX IF NOT EXISTS idx_comm_event_remind ON knowra_community.tbl_comm_event (STAT, STARTS_AT);

CREATE TABLE IF NOT EXISTS knowra_community.tbl_comm_event_rsvp
(
    RSVP_SN     BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    EVENT_SN    BIGINT NOT NULL,
    USER_SN     BIGINT NOT NULL,
    FRST_CRT_DT TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (RSVP_SN),
    CONSTRAINT UK_EVENT_RSVP UNIQUE (EVENT_SN, USER_SN),
    CONSTRAINT FK_EVENT_RSVP_EVENT FOREIGN KEY (EVENT_SN) REFERENCES knowra_community.tbl_comm_event (EVENT_SN) ON DELETE CASCADE
);
