CREATE TABLE IF NOT EXISTS knowra_post.tbl_cmt_hist (
    HIST_SN     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    POST_CMT_SN BIGINT    NOT NULL,
    CMT_CNTNT   TEXT      NOT NULL,
    IMG_URL     VARCHAR(500),
    EDITED_AT   TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_cmt_hist_cmt ON knowra_post.tbl_cmt_hist (POST_CMT_SN, HIST_SN);
