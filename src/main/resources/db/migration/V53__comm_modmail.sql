-- ============================================================================
-- V53: 운영진에게 문의(모드메일)
--
-- 멤버든 아니든(강퇴된 사람의 이의 제기 포함) 커뮤니티 운영진에게 문의를 보낸다. 운영진은 한 문의함을 같이 본다 —
-- 개인 DM 이 아니라 「운영진 팀」에게 가는 것이라, 답한 사람이 바뀌어도 이어진다. 보낸 사람에게는 운영진 개인 이름 대신
-- 「운영진」으로 보인다(운영진끼리는 누가 답했는지 본다).
-- USER_UNREAD / MOD_UNREAD: 상대가 새로 쓴 뒤 아직 안 열었는가. 목록의 점과 관리 배지 숫자에 쓴다.
-- ============================================================================
CREATE TABLE IF NOT EXISTS knowra_community.tbl_comm_modmail
(
    MAIL_SN     BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    COMM_SN     BIGINT NOT NULL,
    USER_SN     BIGINT NOT NULL,
    SUBJECT     VARCHAR(120) NOT NULL,
    STAT        VARCHAR(10)  NOT NULL DEFAULT 'OPEN',
    USER_UNREAD BOOLEAN      NOT NULL DEFAULT FALSE,
    MOD_UNREAD  BOOLEAN      NOT NULL DEFAULT TRUE,
    LAST_AT     TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CREATED_AT  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (MAIL_SN),
    CONSTRAINT FK_MODMAIL_COMM FOREIGN KEY (COMM_SN) REFERENCES knowra_community.tbl_comm (COMM_SN) ON DELETE CASCADE,
    CONSTRAINT FK_MODMAIL_USER FOREIGN KEY (USER_SN) REFERENCES knowra_user.tbl_user (USER_SN) ON DELETE CASCADE,
    CONSTRAINT CK_MODMAIL_STAT CHECK (STAT IN ('OPEN', 'CLOSED'))
);
CREATE INDEX IF NOT EXISTS idx_modmail_comm ON knowra_community.tbl_comm_modmail (COMM_SN, STAT, LAST_AT DESC);
CREATE INDEX IF NOT EXISTS idx_modmail_user ON knowra_community.tbl_comm_modmail (USER_SN, LAST_AT DESC);
COMMENT ON TABLE knowra_community.tbl_comm_modmail IS '운영진에게 문의 — 한 줄이 문의 하나(대화 묶음)';
COMMENT ON COLUMN knowra_community.tbl_comm_modmail.STAT IS 'OPEN 진행 중 / CLOSED 운영진이 닫음(보낸 사람이 다시 쓰면 열린다)';

CREATE TABLE IF NOT EXISTS knowra_community.tbl_comm_modmail_msg
(
    MSG_SN     BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    MAIL_SN    BIGINT NOT NULL,
    SENDER_SN  BIGINT NOT NULL,
    FROM_MOD   BOOLEAN NOT NULL,
    BODY       TEXT NOT NULL,
    CREATED_AT TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (MSG_SN),
    CONSTRAINT FK_MODMAIL_MSG FOREIGN KEY (MAIL_SN) REFERENCES knowra_community.tbl_comm_modmail (MAIL_SN) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_modmail_msg ON knowra_community.tbl_comm_modmail_msg (MAIL_SN, MSG_SN);
COMMENT ON COLUMN knowra_community.tbl_comm_modmail_msg.FROM_MOD IS '운영진 자격으로 쓴 글인가 — 보낸 사람 화면에는 이름 대신 「운영진」';
