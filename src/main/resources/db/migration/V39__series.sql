-- V39: 연재
--
-- 글쓴이가 자기 글을 「1화·2화…」로 묶는다. 순서는 글을 올린 순서(따로 번호를 매기지 않는다).
-- 글 하나는 연재 하나에만. 연재를 지우면 글은 남고 연재 표시만 빠진다(SERIES_SN = NULL).
-- 익명 커뮤니티 글은 넣지 않는다 — 연재가 같은 사람의 글을 한데 묶어 누가 썼는지 드러낸다.
-- ============================================================================
CREATE TABLE IF NOT EXISTS knowra_post.tbl_series (
    SERIES_SN  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_SN    BIGINT       NOT NULL,
    TITLE      VARCHAR(60)  NOT NULL,
    DSCRPTN    VARCHAR(200),
    CREATED_AT TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_series_user ON knowra_post.tbl_series (USER_SN);
ALTER TABLE knowra_post.tbl_post ADD COLUMN IF NOT EXISTS SERIES_SN BIGINT DEFAULT NULL;
CREATE INDEX IF NOT EXISTS idx_post_series ON knowra_post.tbl_post (SERIES_SN);
