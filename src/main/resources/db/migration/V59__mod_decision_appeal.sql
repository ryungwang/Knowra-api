-- V59: 운영 조치 기록과 이의 제기 (EU 디지털서비스법 17·20조 — 이유 통지와 내부 이의 처리)
--
-- 사이트 관리자가 남의 것에 손대면(글·댓글 삭제, 메시지 가림, 계정 정지) 한 줄을 남기고 당사자에게 알린다.
-- 사유는 문장이 아니라 코드(REASON) — 받는 사람의 언어로 화면이 문장을 만든다. 관리자가 덧붙인 설명(DETAIL)만 원문이다.
-- 당사자는 한 번 이의를 낼 수 있고, 처음 결정한 사람이 아닌 관리자가 유지(UPHELD)·뒤집기(REVERSED)로 답한다.
-- 뒤집으면 글·댓글은 되살리고, 메시지는 가림을 풀고, 정지는 푼다.
-- ============================================================================
CREATE TABLE IF NOT EXISTS knowra_user.tbl_mod_decision
(
    DECISION_SN   BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    USER_SN       BIGINT NOT NULL,
    KIND          VARCHAR(20) NOT NULL,
    TARGET_SN     BIGINT DEFAULT NULL,
    REASON        VARCHAR(20) NOT NULL,
    DETAIL        VARCHAR(500) DEFAULT NULL,
    SNAPSHOT      VARCHAR(300) DEFAULT NULL,
    DECIDED_BY    BIGINT DEFAULT NULL,
    CREATED_AT    TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    APPEAL_STAT   VARCHAR(10) NOT NULL DEFAULT 'NONE',
    APPEAL_TEXT   VARCHAR(2000) DEFAULT NULL,
    APPEAL_AT     TIMESTAMP(6) DEFAULT NULL,
    APPEAL_BY     BIGINT DEFAULT NULL,
    APPEAL_NOTE   VARCHAR(500) DEFAULT NULL,
    APPEAL_DONE_AT TIMESTAMP(6) DEFAULT NULL,
    PRIMARY KEY (DECISION_SN),
    CONSTRAINT FK_DECISION_USER FOREIGN KEY (USER_SN) REFERENCES knowra_user.tbl_user (USER_SN) ON DELETE CASCADE,
    CONSTRAINT CK_DECISION_KIND CHECK (KIND IN ('POST_REMOVE', 'CMT_REMOVE', 'MSG_HIDE', 'SUSPEND')),
    CONSTRAINT CK_DECISION_APPEAL CHECK (APPEAL_STAT IN ('NONE', 'OPEN', 'UPHELD', 'REVERSED'))
);
CREATE INDEX IF NOT EXISTS idx_decision_user ON knowra_user.tbl_mod_decision (USER_SN, CREATED_AT DESC);
CREATE INDEX IF NOT EXISTS idx_decision_appeal ON knowra_user.tbl_mod_decision (APPEAL_STAT, APPEAL_AT) WHERE APPEAL_STAT = 'OPEN';
COMMENT ON TABLE knowra_user.tbl_mod_decision IS '사이트 운영 조치와 이의 제기 — 무엇을 왜 했는지, 당사자의 이의와 재검토 결과';
COMMENT ON COLUMN knowra_user.tbl_mod_decision.REASON IS 'SPAM·HARASSMENT·HATE·VIOLENCE·SEXUAL·CHILD_SAFETY·ILLEGAL·PRIVACY·IMPERSONATION·COPYRIGHT·OTHER';
