-- V33: 소셜 계정 여러 개 연결
--
-- 계정 하나에 제공자 하나(tbl_user.SNS_NAME·SNS_ID)뿐이라 구글로 가입한 사람이 카카오를 더 붙이거나, 이메일
-- 가입자가 소셜을 붙일 수 없었다. 연결은 이 표가 단일 진실이다 — (제공자, 제공자 ID)는 한 계정에만.
--
-- ⚠️ tbl_user 의 SNS_NAME·SNS_ID 는 엔티티에서 updatable=false 라, 예전에 「예전 구글 계정에 제공자 ID 묶기」와
-- 「탈퇴 시 SNS_ID 비우기」가 조용히 저장되지 않았다(탈퇴한 사람은 같은 소셜로 다시 가입할 수 없었다).
-- 옮길 때 탈퇴한 계정은 빼서 그 소셜 계정을 풀어 준다.
-- ============================================================================
CREATE TABLE IF NOT EXISTS knowra_user.tbl_user_sns (
    SNS_SN    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_SN   BIGINT       NOT NULL,
    PROVIDER  VARCHAR(20)  NOT NULL,
    SNS_ID    VARCHAR(100) NOT NULL,
    EMAIL     VARCHAR(200) DEFAULT NULL,
    LINKED_AT TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_user_sns UNIQUE (PROVIDER, SNS_ID)
);
CREATE INDEX IF NOT EXISTS idx_user_sns_user ON knowra_user.tbl_user_sns (USER_SN);

INSERT INTO knowra_user.tbl_user_sns (user_sn, provider, sns_id, email)
SELECT user_sn, sns_name, sns_id, email FROM knowra_user.tbl_user
WHERE sns_id IS NOT NULL AND sns_name IS NOT NULL AND actvtn_yn = 'Y'
ON CONFLICT (provider, sns_id) DO NOTHING;
