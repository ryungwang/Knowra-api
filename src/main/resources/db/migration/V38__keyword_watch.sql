CREATE TABLE IF NOT EXISTS knowra_user.tbl_keyword_watch (
    WATCH_SN   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_SN    BIGINT      NOT NULL,
    KEYWORD    VARCHAR(30) NOT NULL,
    CREATED_AT TIMESTAMP   NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_keyword_watch ON knowra_user.tbl_keyword_watch (USER_SN, lower(KEYWORD));
