--  (src/docs/all_DDL.sql 은 2026-04-01 엔티티 기준이라 실제 DB 와 어긋나 쓰지 않는다 —
--   tbl_com_category·tbl_post_cmt_react 누락, tbl_post_cmt_react 의 스키마 위치가 다름.)
--
--  변환 규칙
--    * MySQL DATABASE 6개 -> 한 데이터베이스 안의 SCHEMA 6개.
--      Postgres 는 데이터베이스 간 조인이 안 되므로 catalog 를 그대로 옮길 수 없다.
--    * 식별자는 대문자 그대로 둔다 — Postgres 가 따옴표 없는 이름을 소문자로 접으므로
--      JPA 가 보내는 대문자 참조와 그대로 맞는다.
--    * bigint(20)->BIGINT, int(11)->INTEGER, datetime->TIMESTAMP(6)
--    * AUTO_INCREMENT -> GENERATED BY DEFAULT AS IDENTITY
--    * ON UPDATE current_timestamp() 제거 — Postgres 에 없고 수정일시는 JPA 가 채운다.
--    * MySQL 의 인덱스 이름은 테이블 단위라 스키마 단위인 Postgres 에서 충돌한다.
--      테이블명을 접두사로 붙여 유일하게 만든다.
--    * CHAR(n) -> VARCHAR(n). 엔티티가 평범한 String 이라 Hibernate 는 varchar 를 기대하는데,
--      Postgres 의 CHAR 는 bpchar 로 잡혀 ddl-auto=validate 가 타입 불일치로 기동을 막는다.
--    * COMMENT 는 COMMENT ON 문으로 분리해 보존.
-- =============================================================

