-- ============================================================================
-- V5: 웹 푸시 구독 — 브라우저(기기)마다 한 줄. 같은 사람이 폰·PC 에서 각각 켤 수 있다.
--
-- ENDPOINT 는 브라우저 푸시 서비스(FCM·Mozilla·Apple)가 정해 준 주소라 기기마다 유일하다 — UNIQUE.
-- 다른 계정으로 같은 브라우저에서 다시 켜면 그 줄의 USER_SN 을 바꾼다(한 기기 = 마지막 로그인 계정).
-- P256DH·AUTH 는 RFC 8291 암호화 재료(브라우저 공개키·인증 비밀). 서버만 보낼 수 있는 값이 아니라
-- 이 기기로 "암호화해서" 보내기 위한 값이다.
-- 푸시 서비스가 404/410 을 주면 구독이 죽은 것 — 그 줄을 지운다(WebPushService).
-- ============================================================================
CREATE TABLE IF NOT EXISTS knowra_user.tbl_push_sub
(
    SUB_SN      BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    USER_SN     BIGINT NOT NULL,
    ENDPOINT    VARCHAR(1000) NOT NULL,
    P256DH      VARCHAR(200) NOT NULL,
    AUTH        VARCHAR(100) NOT NULL,
    USER_AGENT  VARCHAR(300) DEFAULT NULL,
    FRST_CRT_DT TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    LAST_OK_DT  TIMESTAMP(6) DEFAULT NULL,
    PRIMARY KEY (SUB_SN),
    CONSTRAINT UK_PUSH_ENDPOINT UNIQUE (ENDPOINT),
    CONSTRAINT FK_PUSH_USER FOREIGN KEY (USER_SN) REFERENCES knowra_user.tbl_user (USER_SN) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_push_user ON knowra_user.tbl_push_sub (USER_SN);
