CREATE TABLE IF NOT EXISTS knowra_com.tbl_banned_word
(
    WORD_SN     BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    WORD        VARCHAR(50) NOT NULL,
    CREATED_BY  BIGINT NOT NULL,
    FRST_CRT_DT TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (WORD_SN),
    CONSTRAINT uq_banned_word UNIQUE (WORD)
);
