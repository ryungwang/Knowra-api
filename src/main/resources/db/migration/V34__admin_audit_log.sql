CREATE TABLE IF NOT EXISTS knowra_com.tbl_admin_log (
    LOG_SN      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ADMIN_SN    BIGINT       NOT NULL,
    ACTION      VARCHAR(30)  NOT NULL,
    TARGET_KIND VARCHAR(10)  DEFAULT NULL,
    TARGET_SN   BIGINT       DEFAULT NULL,
    DETAIL      VARCHAR(300) DEFAULT NULL,
    CREATED_AT  TIMESTAMP    NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_admin_log_sn ON knowra_com.tbl_admin_log (LOG_SN DESC);
