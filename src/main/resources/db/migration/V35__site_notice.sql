-- ============================================================================
-- V35: 사이트 전체 공지 배너
--
-- 점검·정책 변경을 모든 사용자에게 알릴 수단이 없었다. 지금 보이는 공지는 ACTIVE 이고 기간 안인 것 중 가장 최근 하나.
-- 링크는 사이트 안 경로(/...)나 https 만 — 공지 링크가 피싱 통로가 되면 안 된다.
-- ============================================================================
CREATE TABLE IF NOT EXISTS knowra_com.tbl_site_notice (
    NOTICE_SN  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MESSAGE    VARCHAR(300) NOT NULL,
    LINK       VARCHAR(300) DEFAULT NULL,
    LEVEL      VARCHAR(10)  NOT NULL DEFAULT 'INFO',
    STARTS_AT  TIMESTAMP    NOT NULL,
    ENDS_AT    TIMESTAMP    DEFAULT NULL,
    ACTIVE     BOOLEAN      NOT NULL DEFAULT TRUE,
    CREATED_BY BIGINT       NOT NULL,
    CREATED_AT TIMESTAMP    NOT NULL
);
