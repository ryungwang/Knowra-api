-- ============================================================================
-- V60: 저작권 침해 신고(게시 중단 요청)
--
-- 권리자는 회원이 아닐 수 있어 로그인 없이 받는다. DMCA 512(c)(3)·한국 저작권법 103조가 요구하는 항목을 받는다:
-- 신고자 이름·연락처, 침해된 저작물 설명, 침해 글 주소, 선의 진술, 정확성·권한 진술, 서명(이름 입력).
-- 받아들이면(ACTED) 글을 내리고 tbl_mod_decision(사유 COPYRIGHT)으로 글쓴이에게 알린다 — 글쓴이의 반론은 그 이의 제기로 받는다.
-- 같은 글쓴이에게 ACTED 가 쌓이면 관리 화면에 표시한다(반복 침해자 정책: 약관 7항).
-- ============================================================================
CREATE TABLE IF NOT EXISTS knowra_user.tbl_copyright_notice
(
    NOTICE_SN     BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    CLAIMANT_NAME VARCHAR(100) NOT NULL,
    CLAIMANT_EMAIL VARCHAR(200) NOT NULL,
    CLAIMANT_ORG  VARCHAR(200) DEFAULT NULL,
    WORK_DESC     VARCHAR(2000) NOT NULL,
    ORIGINAL_URL  VARCHAR(500) DEFAULT NULL,
    TARGET_URL    VARCHAR(500) NOT NULL,
    TARGET_POST_SN BIGINT DEFAULT NULL,
    TARGET_USER_SN BIGINT DEFAULT NULL,
    SIGNATURE     VARCHAR(100) NOT NULL,
    REPORTER_SN   BIGINT DEFAULT NULL,
    IP            VARCHAR(64) DEFAULT NULL,
    STAT          VARCHAR(10) NOT NULL DEFAULT 'OPEN',
    HANDLED_BY    BIGINT DEFAULT NULL,
    HANDLED_AT    TIMESTAMP(6) DEFAULT NULL,
    NOTE          VARCHAR(500) DEFAULT NULL,
    CREATED_AT    TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (NOTICE_SN),
    CONSTRAINT CK_COPYRIGHT_STAT CHECK (STAT IN ('OPEN', 'ACTED', 'REJECTED'))
);
CREATE INDEX IF NOT EXISTS idx_copyright_stat ON knowra_user.tbl_copyright_notice (STAT, CREATED_AT);
CREATE INDEX IF NOT EXISTS idx_copyright_target_user ON knowra_user.tbl_copyright_notice (TARGET_USER_SN) WHERE STAT = 'ACTED';
COMMENT ON TABLE knowra_user.tbl_copyright_notice IS '저작권 침해 신고 — 권리자의 게시 중단 요청과 처리';
