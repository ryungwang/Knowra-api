-- V58: 약관·개인정보 처리방침 동의와 나이 확인 기록
--
-- 가입할 때(그리고 문서가 바뀌면 다시) 무엇에, 어느 판에, 언제 동의했는지 남긴다 — GDPR·개인정보보호법의
-- 「동의를 받았음을 증명」할 근거다. 한 줄 = 한 번의 동의. 같은 사람·종류의 가장 최근 판이 지금 유효한 동의다.
-- KIND: TERMS(이용약관) · PRIVACY(개인정보 처리방침) · AGE(나이 확인 — VERSION 에 그때의 최소 나이)
-- ============================================================================
CREATE TABLE IF NOT EXISTS knowra_user.tbl_user_consent
(
    CONSENT_SN BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    USER_SN    BIGINT NOT NULL,
    KIND       VARCHAR(16) NOT NULL,
    VERSION    VARCHAR(32) NOT NULL,
    AGREED_AT  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    IP         VARCHAR(64) DEFAULT NULL,
    PRIMARY KEY (CONSENT_SN),
    CONSTRAINT FK_CONSENT_USER FOREIGN KEY (USER_SN) REFERENCES knowra_user.tbl_user (USER_SN) ON DELETE CASCADE,
    CONSTRAINT CK_CONSENT_KIND CHECK (KIND IN ('TERMS', 'PRIVACY', 'AGE'))
);
CREATE INDEX IF NOT EXISTS idx_consent_user ON knowra_user.tbl_user_consent (USER_SN, KIND, AGREED_AT DESC);
COMMENT ON TABLE knowra_user.tbl_user_consent IS '약관·처리방침 동의와 나이 확인 기록 — 동의를 받았다는 증거';
