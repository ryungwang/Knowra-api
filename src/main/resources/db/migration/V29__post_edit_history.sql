-- 제목·본문을 남긴다 — 제목이나 본문이 실제로 바뀐 때만(말머리·공지 전환 같은 건 빼고).
-- 「수정됨」은 이 기록으로 판단한다 — MDFCN_DT 는 고정(핀) 같은 내용과 상관없는 저장에도 바뀐다.
