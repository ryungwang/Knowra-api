CREATE TABLE IF NOT EXISTS knowra_post.tbl_post_hist (
    HIST_SN    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    POST_SN    BIGINT       NOT NULL,
    POST_TTL   VARCHAR(500) NOT NULL,
    POST_CNTNT TEXT         NOT NULL,
    EDITED_BY  BIGINT       NOT NULL,
    EDITED_AT  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_post_hist_post ON knowra_post.tbl_post_hist (POST_SN, HIST_SN);
