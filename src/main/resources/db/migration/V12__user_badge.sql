CREATE TABLE IF NOT EXISTS knowra_user.tbl_user_badge
(
    USER_BADGE_SN BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    USER_SN       BIGINT NOT NULL,
    BADGE_KEY     VARCHAR(40) NOT NULL,
    EARNED_AT     TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (USER_BADGE_SN),
    CONSTRAINT UK_USER_BADGE UNIQUE (USER_SN, BADGE_KEY),
    CONSTRAINT FK_USER_BADGE_USER FOREIGN KEY (USER_SN) REFERENCES knowra_user.tbl_user (USER_SN) ON DELETE CASCADE
);
