--
-- 서버 ERROR 로그와 화면(브라우저) 오류를 "같은 오류는 한 줄"로 모은다. FINGERPRINT 는
-- 출처 + 예외 종류 + 우리 코드 쪽 스택 몇 줄의 해시라, 같은 곳에서 난 같은 오류는 CNT 만 오른다.
-- 해결(RESOLVED)로 표시한 오류가 다시 나면 자동으로 다시 열린다(재발을 놓치지 않게).
-- ============================================================================
CREATE TABLE IF NOT EXISTS knowra_com.tbl_err_log
(
    ERR_SN       BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    FINGERPRINT  VARCHAR(64) NOT NULL,
    SOURCE       VARCHAR(10) NOT NULL,          -- API | WEB
    ERR_TYPE     VARCHAR(200) NOT NULL,
    MESSAGE      VARCHAR(1000) NOT NULL DEFAULT '',
    STACK        TEXT NOT NULL DEFAULT '',
    LAST_PATH    VARCHAR(300) DEFAULT NULL,
    LAST_USER_SN BIGINT DEFAULT NULL,
    CNT          INT NOT NULL DEFAULT 1,
    RESOLVED     BOOLEAN NOT NULL DEFAULT FALSE,
    FIRST_SEEN   TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    LAST_SEEN    TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (ERR_SN),
    CONSTRAINT uq_err_log_fp UNIQUE (FINGERPRINT)
);
CREATE INDEX IF NOT EXISTS idx_err_log_open ON knowra_com.tbl_err_log (RESOLVED, LAST_SEEN DESC);
