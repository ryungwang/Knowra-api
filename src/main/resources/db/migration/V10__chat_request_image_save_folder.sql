ALTER TABLE knowra_user.tbl_chat_msg ADD COLUMN IF NOT EXISTS IMG_URL VARCHAR(300) DEFAULT NULL;

CREATE TABLE IF NOT EXISTS knowra_post.tbl_post_save_folder
(
    FOLDER_SN   BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    USER_SN     BIGINT NOT NULL,
    NAME        VARCHAR(40) NOT NULL,
    FRST_CRT_DT TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (FOLDER_SN),
    CONSTRAINT UK_SAVE_FOLDER_NAME UNIQUE (USER_SN, NAME),
    CONSTRAINT FK_SAVE_FOLDER_USER FOREIGN KEY (USER_SN) REFERENCES knowra_user.tbl_user (USER_SN) ON DELETE CASCADE
);
ALTER TABLE knowra_post.tbl_post_save ADD COLUMN IF NOT EXISTS FOLDER_SN BIGINT DEFAULT NULL;
DO $$ BEGIN
    ALTER TABLE knowra_post.tbl_post_save ADD CONSTRAINT FK_POST_SAVE_FOLDER FOREIGN KEY (FOLDER_SN)
        REFERENCES knowra_post.tbl_post_save_folder (FOLDER_SN) ON DELETE SET NULL;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
