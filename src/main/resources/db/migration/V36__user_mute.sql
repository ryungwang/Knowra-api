-- 차단은 DM·알림까지 끊는 강한 조치라, 「그냥 이 사람 글이 안 보였으면」 하는 사람에게 너무 세다. 숨기기는 한쪽만이다 —
-- 상대는 모르고, 상대는 내 글을 계속 본다. 숨긴 사람의 글은 내 피드·목록·검색에서 빠지고(링크로 열면 열린다),
-- 댓글은 접힌 채 보이고, 그 사람의 반응은 알림으로 오지 않는다.
-- ============================================================================
CREATE TABLE IF NOT EXISTS knowra_user.tbl_user_mute (
    MUTE_SN    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_SN    BIGINT    NOT NULL,
    MUTED_SN   BIGINT    NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT uq_user_mute UNIQUE (USER_SN, MUTED_SN)
);
