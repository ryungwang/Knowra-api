-- ============================================================================
-- V24: 커뮤니티 운영 기록
--
-- 운영진이 여럿이면 「누가 이 사람을 내보냈나」「누가 이 글을 지웠나」를 물을 곳이 없었다.
-- 운영진(OWNER/ADMIN)만 본다. DETAIL 은 그때의 글 제목·바뀐 항목 같은 설명 — 글이 지워져도 읽히게 남긴다.
-- 익명 커뮤니티의 글·댓글 기록엔 작성자(TARGET_USER_SN)를 남기지 않는다 — 기록이 익명을 깨면 안 된다.
-- ============================================================================
CREATE TABLE IF NOT EXISTS knowra_community.tbl_comm_mod_log (
    LOG_SN          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COMM_SN         BIGINT       NOT NULL,
    ACTOR_SN        BIGINT       NOT NULL,
    ACTION          VARCHAR(30)  NOT NULL,
    TARGET_USER_SN  BIGINT       DEFAULT NULL,
    TARGET_POST_SN  BIGINT       DEFAULT NULL,
    DETAIL          VARCHAR(300) DEFAULT NULL,
    CREATED_AT      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_comm_mod_log_comm ON knowra_community.tbl_comm_mod_log (COMM_SN, LOG_SN DESC);
