-- ============================================================================
-- V31: 말머리(글 분류)
--
-- 커뮤니티마다 「질문·정보·잡담」 같은 분류를 운영진이 정하고, 글에 하나 달아 걸러 본다. 커뮤니티당 10개까지.
-- 색은 정해진 이름(blue·green…)만 저장한다 — 임의 색 값을 받아 화면에 그대로 넣지 않는다.
-- 말머리를 지우면 그걸 단 글은 말머리 없음(NULL)이 된다.
-- ============================================================================
CREATE TABLE IF NOT EXISTS knowra_community.tbl_comm_flair (
    FLAIR_SN   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COMM_SN    BIGINT      NOT NULL,
    NAME       VARCHAR(20) NOT NULL,
    COLOR      VARCHAR(12) NOT NULL DEFAULT 'gray',
    ORD        INT         NOT NULL DEFAULT 0,
    CREATED_AT TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_comm_flair_comm ON knowra_community.tbl_comm_flair (COMM_SN, ORD);
ALTER TABLE knowra_post.tbl_post ADD COLUMN IF NOT EXISTS FLAIR_SN BIGINT DEFAULT NULL;
CREATE INDEX IF NOT EXISTS idx_post_flair ON knowra_post.tbl_post (FLAIR_SN);
