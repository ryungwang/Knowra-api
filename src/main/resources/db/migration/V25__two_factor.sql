-- V25: 2단계 인증(TOTP)
--
-- TOTP_SECRET 이 있고 TOTP_ENABLED_AT 이 있으면 켜진 것이다. 비밀번호(또는 소셜)가 맞아도 인증 앱 코드를
-- 한 번 더 받는다. 복구 코드는 해시만 남긴다(SHA-256) — 쓰면 USED_AT 이 찍히고 다시 못 쓴다.
-- ============================================================================
ALTER TABLE knowra_user.tbl_user ADD COLUMN IF NOT EXISTS TOTP_SECRET VARCHAR(64) DEFAULT NULL;
ALTER TABLE knowra_user.tbl_user ADD COLUMN IF NOT EXISTS TOTP_ENABLED_AT TIMESTAMP DEFAULT NULL;

CREATE TABLE IF NOT EXISTS knowra_user.tbl_user_recovery_code (
    CODE_SN     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_SN     BIGINT      NOT NULL,
    CODE_HASH   VARCHAR(64) NOT NULL,
    USED_AT     TIMESTAMP   DEFAULT NULL,
    CREATED_AT  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_recovery_code_user ON knowra_user.tbl_user_recovery_code (USER_SN);
