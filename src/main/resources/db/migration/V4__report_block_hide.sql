-- ============================================================================
-- V4: 신고 · 차단 · 숨기기 — 악성 글·유저에 대응할 수단이 전혀 없었다.
--
-- 신고(tbl_report): 글·댓글·유저를 사유와 함께 신고한다. 같은 사람이 같은 대상을 두 번 신고하지
--   못하게 UNIQUE. 처리 상태(OPEN/RESOLVED/DISMISSED)는 관리자 콘솔이 바꾼다.
-- 차단(tbl_user_block): 차단하면 그 사람의 글·댓글이 내 피드에서 사라지고, 서로 채팅·알림이 끊긴다.
-- 숨기기(tbl_post_hide): 글 하나만 내 피드에서 치운다. 작성자와는 무관.
-- 정지(tbl_user.status): 'Y' 정상 · 'S' 정지. 정지된 계정은 로그인이 거절된다.
-- ============================================================================
CREATE TABLE IF NOT EXISTS knowra_user.tbl_report
(
    REPORT_SN   BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    REPORTER_SN BIGINT NOT NULL,
    TARGET_KIND VARCHAR(10) NOT NULL,
    TARGET_SN   BIGINT NOT NULL,
    REASON      VARCHAR(20) NOT NULL,
    DETAIL      VARCHAR(500) DEFAULT NULL,
    STAT        VARCHAR(10) NOT NULL DEFAULT 'OPEN',
    HANDLED_BY  BIGINT DEFAULT NULL,
    HANDLED_AT  TIMESTAMP(6) DEFAULT NULL,
    FRST_CRT_DT TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (REPORT_SN),
    CONSTRAINT UK_REPORT_ONCE UNIQUE (REPORTER_SN, TARGET_KIND, TARGET_SN),
    CONSTRAINT FK_REPORT_USER FOREIGN KEY (REPORTER_SN) REFERENCES knowra_user.tbl_user (USER_SN)
);
CREATE INDEX IF NOT EXISTS idx_report_stat ON knowra_user.tbl_report (STAT, FRST_CRT_DT);

CREATE TABLE IF NOT EXISTS knowra_user.tbl_user_block
(
    BLOCK_SN    BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    USER_SN     BIGINT NOT NULL,
    BLOCKED_SN  BIGINT NOT NULL,
    FRST_CRT_DT TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (BLOCK_SN),
    CONSTRAINT UK_USER_BLOCK UNIQUE (USER_SN, BLOCKED_SN),
    CONSTRAINT FK_BLOCK_USER FOREIGN KEY (USER_SN) REFERENCES knowra_user.tbl_user (USER_SN),
    CONSTRAINT FK_BLOCK_TARGET FOREIGN KEY (BLOCKED_SN) REFERENCES knowra_user.tbl_user (USER_SN)
);

CREATE TABLE IF NOT EXISTS knowra_post.tbl_post_hide
(
    HIDE_SN     BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    USER_SN     BIGINT NOT NULL,
    POST_SN     BIGINT NOT NULL,
    FRST_CRT_DT TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (HIDE_SN),
    CONSTRAINT UK_POST_HIDE UNIQUE (USER_SN, POST_SN)
);
