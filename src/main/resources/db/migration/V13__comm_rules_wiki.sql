-- V13: 커뮤니티 규칙 · 위키
--
-- tbl_comm_rule: 운영진이 쓰는 규칙 목록(최대 10개, 순서대로). 규칙이 있는 커뮤니티는 참여할 때 동의해야 하고,
--   그 시각을 멤버 줄(RULES_AGREED_AT)에 남긴다 — 나중에 "규칙을 몰랐다"는 말이 나와도 확인할 수 있게.
-- tbl_comm_page: 고정 위키 페이지(최대 20개). 본문은 글과 같은 HTML 허용 목록으로 정리해 저장한다.
--   비공개 커뮤니티의 규칙·위키는 멤버에게만 보인다.
-- ============================================================================
CREATE TABLE IF NOT EXISTS knowra_community.tbl_comm_rule
(
    RULE_SN   BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    COMM_SN   BIGINT NOT NULL,
    ORD       INT NOT NULL,
    TITLE     VARCHAR(60) NOT NULL,
    BODY      VARCHAR(300) NOT NULL DEFAULT '',
    PRIMARY KEY (RULE_SN)
);
CREATE INDEX IF NOT EXISTS idx_comm_rule ON knowra_community.tbl_comm_rule (COMM_SN, ORD);

CREATE TABLE IF NOT EXISTS knowra_community.tbl_comm_page
(
    PAGE_SN    BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    COMM_SN    BIGINT NOT NULL,
    SLUG       VARCHAR(40) NOT NULL,
    TITLE      VARCHAR(80) NOT NULL,
    CONTENT    TEXT NOT NULL DEFAULT '',
    ORD        INT NOT NULL DEFAULT 0,
    UPDATED_BY BIGINT NOT NULL,
    UPDATED_AT TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (PAGE_SN),
    CONSTRAINT UK_COMM_PAGE_SLUG UNIQUE (COMM_SN, SLUG)
);

ALTER TABLE knowra_community.tbl_comm_mbr ADD COLUMN IF NOT EXISTS RULES_AGREED_AT TIMESTAMP(6) DEFAULT NULL;
